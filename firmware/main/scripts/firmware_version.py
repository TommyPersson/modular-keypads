# Makes the date the firmware is built and the git commit it's built from its version, e.g. "2026-10-24-2444b54", or
# "2026-10-24-2444b54-dirty" when the firmware has uncommitted changes, in local builds as well as in CI. Without git,
# or outside a repository, the commit is "unknown".
#
# The date is the build's, in UTC, so that builds of the same commit on different days can be told apart.
#
# The version is written to a generated header, which only FirmwareVersion.cpp includes, so that a new commit
# recompiles that file rather than all of them, as changing the defines of the whole build would. The header is only
# rewritten when the version changes.

import os
import subprocess
from datetime import datetime, timezone

Import("env")


def git(*args):
    return subprocess.run(
        ["git", *args],
        cwd=env["PROJECT_DIR"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def git_commit():
    try:
        commit = git("rev-parse", "--short=7", "HEAD")
        # Only changes to the firmware itself count, not to e.g. the PCBs or the config tool
        is_dirty = git("status", "--porcelain", "--", ".") != ""
    except (OSError, subprocess.CalledProcessError):
        return "unknown"

    return f"{commit}-dirty" if is_dirty else commit


def firmware_version():
    build_date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    return f"{build_date}-{git_commit()}"


def write_if_changed(path, content):
    if os.path.exists(path):
        with open(path, encoding="utf-8") as file:
            if file.read() == content:
                return

    with open(path, "w", encoding="utf-8") as file:
        file.write(content)


version = firmware_version()
print(f"Firmware version: {version}")

generated_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(generated_dir, exist_ok=True)

write_if_changed(
    os.path.join(generated_dir, "firmware_version.h"),
    "// Generated by scripts/firmware_version.py\n"
    "#pragma once\n"
    f"#define FIRMWARE_VERSION \"{version}\"\n",
)

env.Append(CPPPATH=[generated_dir])
